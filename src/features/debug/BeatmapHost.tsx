import { useState, useEffect } from 'react';
import { getSong, getBeatmap } from '../../core/api/client';
import type { SongDetail, ChordLyric } from '../../core/api/client';
import BeatmapEditorModal from '../noodle/BeatmapEditorModal';
import { generateBeatmap, isTabLine } from '../noodle/songUtils';

interface Props {
  songId: string;
  onClose: () => void;
  onSaved: () => void;
}

// Hosts the Noodle page's beatmap editor on its own, loading the song and its current beatmap
export default function BeatmapHost({ songId, onClose, onSaved }: Props) {
  const [song, setSong] = useState<SongDetail | null>(null);
  const [draft, setDraft] = useState<number[]>([]);
  const [submitted, setSubmitted] = useState(false);

  useEffect(() => {
    let cancelled = false;
    getSong(songId).then(async s => {
      const chordOnly = s.chordLines.filter(l => !isTabLine(l)) as ChordLyric[];
      const generated = generateBeatmap(chordOnly, s.timeSignature ?? 4);
      const saved = await getBeatmap(songId).then(b => b.beats).catch(() => null);
      if (cancelled) return;
      setSong(s);
      setDraft(saved && saved.length >= generated.length ? saved : generated);
    }).catch(() => { if (!cancelled) onClose(); });
    return () => { cancelled = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [songId]);

  if (!song || draft.length === 0) return null;

  return (
    <BeatmapEditorModal
      contentLines={song.chordLines}
      beatmapDraft={draft}
      setBeatmapDraft={setDraft}
      beatmapSubmitSuccess={submitted}
      setBeatmapSubmitSuccess={setSubmitted}
      activeSongId={songId}
      song={song}
      setBeatmap={() => {}}
      setBeatmapAutoGenerated={() => {}}
      setShowBeatmapEditor={show => { if (!show) { onClose(); onSaved(); } }}
    />
  );
}
